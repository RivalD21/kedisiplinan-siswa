// Generate attendance records for past 30 days
export function generateSeedAttendance(): Attendance[] {
  const attendances: Attendance[] = [];
  const classes = ['X RPL 1', 'X TKJ 1', 'XI RPL 2', 'XI TKJ 1', 'XII RPL 1', 'XII TKJ 2'];
  const today = new Date('2026-03-06');

  // Generate 14 school days
  const dates: string[] = [];
  for (let i = 0; i < 20; i++) {
    const d = new Date(today);
    d.setDate(today.getDate() - i);
    // Exclude Sundays (0) and Saturdays (6)
    if (d.getDay() !== 0 && d.getDay() !== 6) {
      dates.push(d.toISOString().split('T')[0]);
    }
    if (dates.length >= 12) break;
  }

  let attId = 1;
  dates.forEach((date) => {
    initialStudents.forEach((student) => {
      // Deterministic variations based on student id and date
      const hash = (student.nis.charCodeAt(student.nis.length - 1) + date.charCodeAt(date.length - 1)) % 100;
      let status: 'Hadir' | 'Sakit' | 'Izin' | 'Alpha' | 'Terlambat' = 'Hadir';
      let jam_masuk = '06:45';
      let keterangan = '';

      if (student.id === 'std-3' && hash < 25) {
        status = 'Alpha';
        keterangan = 'Tanpa kabar / tidak masuk';
        jam_masuk = '';
      } else if (student.id === 'std-7' && hash < 20) {
        status = 'Terlambat';
        jam_masuk = '07:25';
        keterangan = 'Terlambat 25 menit';
      } else if (student.id === 'std-14' && hash < 15) {
        status = 'Sakit';
        keterangan = 'Surat dokter terlampir';
        jam_masuk = '';
      } else if (hash < 3) {
        status = 'Sakit';
        keterangan = 'Demam';
        jam_masuk = '';
      } else if (hash < 6) {
        status = 'Izin';
        keterangan = 'Acara keluarga';
        jam_masuk = '';
      } else if (hash < 9) {
        status = 'Terlambat';
        jam_masuk = '07:15';
        keterangan = 'Macet jalan raya';
      } else if (hash < 11) {
        status = 'Alpha';
        keterangan = 'Tanpa keterangan';
        jam_masuk = '';
      }

      attendances.push({
        id: `att-${attId++}`,
        student_id: student.id,
        tanggal: date,
        status,
        jam_masuk: status === 'Hadir' || status === 'Terlambat' ? jam_masuk : undefined,
        keterangan: keterangan || undefined,
        created_by: 'Siti Rahmawati, S.Pd.',
        created_at: `${date}T07:00:00Z`,
        updated_at: `${date}T07:00:00Z`,
      });
    });
  });

  return attendances;
}
